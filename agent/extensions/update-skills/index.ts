import { existsSync, lstatSync, readdirSync, readFileSync, realpathSync, statSync } from "node:fs";
import { basename, dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { getAgentDir, type ExtensionAPI } from "@earendil-works/pi-coding-agent";

type Kind = "repository" | "github" | "package" | "tool" | "symlink" | "personal";
const repositorySkills = resolve(realpathSync(dirname(fileURLToPath(import.meta.url))), "../../skills");
type Skill = { name: string; dir: string; file: string; scope: "user" | "project" | "package"; kind: Kind; detail: string; update?: string; packageSource?: string };
const gws = new Set(["gws-shared", "gws-docs", "gws-docs-write", "gws-drive", "gws-drive-upload", "gws-sheets", "gws-sheets-append", "gws-sheets-read"]);
const trim = (text: string, limit = 6000) => text.trim().slice(0, limit);

function frontmatter(file: string) {
  const text = readFileSync(file, "utf8");
  const match = text.match(/^---\n([\s\S]*?)\n---/);
  return match?.[1] ?? "";
}
function value(front: string, key: string) {
  return front.match(new RegExp(`^\\s*${key}:\\s*["']?([^\\n"']+)["']?\\s*$`, "m"))?.[1]?.trim();
}
function roots(cwd: string, settings: any) {
  const agent = getAgentDir();
  const result: { root: string; scope: Skill["scope"]; source?: string }[] = [{ root: join(agent, "skills"), scope: "user" }];
  const project = join(cwd, ".pi", "skills");
  if (existsSync(project)) result.push({ root: project, scope: "project" });
  for (const entry of settings?.packages ?? []) {
    const source = typeof entry === "string" ? entry : entry.source;
    if (typeof source !== "string" || !source.startsWith("npm:")) continue;
    const name = source.slice(4).replace(/@(?=[^/]+$).*/, "");
    result.push({ root: join(agent, "npm", "node_modules", name, "skills"), scope: "package", source });
  }
  return result;
}
function scan(root: string, scope: Skill["scope"], source?: string): Skill[] {
  if (!existsSync(root)) return [];
  const found: Skill[] = [];
  const walk = (dir: string) => {
    let children: string[];
    try { children = readdirSync(dir); } catch { return; }
    if (children.includes("SKILL.md")) {
      const file = join(dir, "SKILL.md"); const front = frontmatter(file); const name = value(front, "name") ?? basename(dir);
      const link = lstatSync(dir).isSymbolicLink(); const github = value(front, "github-repo");
      const target = link ? realpathSync(dir) : undefined;
      const repository = target?.startsWith(`${repositorySkills}${sep}`);
      let kind: Kind = repository ? "repository" : github ? "github" : link ? "symlink" : gws.has(name) ? "tool" : scope === "package" ? "package" : "personal";
      let detail = github ? github.replace(/^https:\/\/github\.com\//, "") : "";
      let update: string | undefined; let packageSource = source;
      if (kind === "repository") { detail = `pi-setup checkout → ${target}`; update = "Edit in pi-setup, run ./setup.sh, then /reload when ready"; }
      if (kind === "github") update = "gh skill update";
      if (kind === "package") { detail = source ?? "Pi package"; update = source ? `pi update ${source}` : undefined; }
      if (kind === "tool") { detail = "googleworkspace/cli · generated by gws"; update = "Update gws, then regenerate selected skills deliberately"; }
      if (kind === "symlink") { detail = `→ ${realpathSync(dir)}`; update = "Update the owning tool"; }
      if (kind === "personal") detail = "local";
      found.push({ name, dir, file, scope, kind, detail, update, packageSource }); return;
    }
    for (const child of children) { const path = join(dir, child); try { if (statSync(path).isDirectory()) walk(path); } catch {} }
  };
  walk(root); return found;
}
function inventory(cwd: string, settings: any) {
  const byName = new Map<string, Skill>();
  for (const root of roots(cwd, settings)) for (const skill of scan(root.root, root.scope, root.source)) if (!byName.has(skill.name)) byName.set(skill.name, skill);
  return [...byName.values()].sort((a, b) => a.name.localeCompare(b.name));
}
function display(skills: Skill[]) {
  const rows = skills.map(s => `${s.name.padEnd(28)} ${s.scope.padEnd(8)} ${s.kind.padEnd(9)} ${s.detail}`);
  return `Available skills · ${skills.length}\n\nName                         Scope    Owner     Source / update\n${rows.join("\n")}`;
}

export default function (pi: ExtensionAPI) {
  let running = false;
  pi.registerCommand("skills", {
    description: "List available skills and their owner/update mechanism; /skills update refreshes managed user skills",
    handler: async (args, ctx) => {
      const [action, name] = args.trim().split(/\s+/, 2);
      let settings: any = {};
      try { settings = JSON.parse(readFileSync(join(getAgentDir(), "settings.json"), "utf8")); } catch { /* Package discovery is optional; user skills remain available. */ }
      const skills = inventory(ctx.cwd, settings);
      if (!action) { ctx.ui.notify(display(skills), "info"); return; }
      if (action === "details" && name) {
        const skill = skills.find(s => s.name === name);
        if (!skill) { ctx.ui.notify(`No available skill named ${name}.`, "error"); return; }
        ctx.ui.notify(`${skill.name}\nPath: ${skill.dir}\nScope: ${skill.scope}\nOwner: ${skill.kind}\nSource: ${skill.detail}\nUpdate: ${skill.update ?? "None; personal/local skill."}`, "info"); return;
      }
      if (action !== "update" || name) { ctx.ui.notify("Usage: /skills, /skills details <name>, or /skills update", "error"); return; }
      if (running) { ctx.ui.notify("A skill update is already running in this session.", "warning"); return; }
      running = true; ctx.ui.setStatus("skills", "Updating managed skills…");
      try {
        const userGithub = skills.filter(s => s.scope === "user" && s.kind === "github");
        const packages = [...new Set(skills.filter(s => s.kind === "package" && s.packageSource).map(s => s.packageSource!))];
        const skipped = skills.filter(s => s.kind === "repository" || s.kind === "tool" || s.kind === "symlink" || s.kind === "personal");
        const output: string[] = [];
        let changed = false;
        const changedOutput = (text: string) => /\bupdated\b|\binstalled\b|[1-9]\d* update\(s\) available/i.test(text) && !/all skills are up to date|already current/i.test(text);
        if (userGithub.length) {
          const result = await pi.exec("gh", ["skill", "update", ...userGithub.map(skill => skill.name), "--dir", join(getAgentDir(), "skills"), "--unpin"], { cwd: ctx.cwd, timeout: 120_000 });
          const text = trim([result.stdout, result.stderr].filter(Boolean).join("\n"));
          output.push(`GitHub skills:\n${text || (result.code === 0 ? "Already current." : `failed (exit ${result.code})`)}`);
          changed ||= changedOutput(text);
          if (result.code !== 0 || result.killed) throw new Error(output.at(-1));
        }
        for (const source of packages) {
          const result = await pi.exec("pi", ["update", source], { cwd: ctx.cwd, timeout: 120_000 });
          const text = trim([result.stdout, result.stderr].filter(Boolean).join("\n"));
          output.push(`Package ${source}:\n${text || (result.code === 0 ? "Already current." : `failed (exit ${result.code})`)}`);
          changed ||= changedOutput(text);
          if (result.code !== 0 || result.killed) throw new Error(output.at(-1));
        }
        if (skipped.length) output.push(`Not auto-updated:\n${skipped.map(s => `• ${s.name}: ${s.update ?? "personal/local"}`).join("\n")}`);
        ctx.ui.notify(output.join("\n\n"), "info");
        if (changed) {
          await ctx.waitForIdle();
          ctx.ui.setStatus("skills", "Updates complete; reloading resources…");
          await ctx.reload();
        }
      } catch (error) { ctx.ui.notify(`Skill update failed: ${error instanceof Error ? error.message : String(error)}`, "error"); }
      finally { running = false; ctx.ui.setStatus("skills", undefined); }
    },
  });
}
